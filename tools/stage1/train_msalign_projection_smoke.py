class MoleculeEmbeddingStore:
    def __init__(
        self,
        chemberta: dict[str, Any] | None,
        mol_pooling: str,
        fingerprint_cache: Path | None = None,
        additional_fingerprint_caches: list[Path] | None = None,
        preload_sparse_features: bool = False,
        mol_blocks: list[str] | tuple[str, ...] | None = None,
    ) -> None:
        self.chemberta = chemberta
        self.mol_pooling = mol_pooling
        self.size = len(chemberta["smiles_to_index"]) if chemberta is not None else 0
        self.smiles_sha256: str | None = None
        self.sparse: Any | None = None
        self.sparse_caches: list[Any] = []
        self.feature_caches: dict[str, Any] = {}
        self.parts = tuple(mol_blocks) if mol_blocks is not None else SPARSE_POOLING_PARTS.get(mol_pooling)
        self.block_names: list[str] = []
        self.block_dims: list[int] = []
        self.dense: torch.Tensor | None = None
        if self.parts is None:
            if chemberta is None:
                raise ValueError(f"mol_pooling={mol_pooling!r} requires --chemberta-cache")
            self.dense = load_mol_embeddings(chemberta, mol_pooling)
            self.dim = int(self.dense.shape[1])
            self.block_names = [mol_pooling]
            self.block_dims = [self.dim]
            return
        if fingerprint_cache is None:
            raise ValueError(f"mol_pooling={mol_pooling!r} requires --fingerprint-cache")
        cache_paths = [fingerprint_cache, *(additional_fingerprint_caches or [])]
        expected_digest: str | None = None
        for cache_path in cache_paths:
            cache = load_sparse_feature_cache(cache_path)
            if self.size == 0:
                self.size = cache.rows
            if cache.rows != self.size:
                raise ValueError(
                    f"Sparse fingerprint rows do not match molecule cache: {cache.rows} != {self.size}"
                )
            if expected_digest is None:
                expected_digest = cache.smiles_sha256
            elif cache.smiles_sha256 and expected_digest and cache.smiles_sha256 != expected_digest:
                raise ValueError(f"Sparse fingerprint SMILES digest mismatch in {cache_path}")
            for name in cache.features:
                if name in self.feature_caches:
                    raise ValueError(f"Duplicate sparse feature {name!r} across fingerprint manifests")
                self.feature_caches[name] = cache
            self.sparse_caches.append(cache)
        self.smiles_sha256 = expected_digest
        self.sparse = self.sparse_caches[0]
        for part in self.parts:
            if part in ("mean", "cls"):
                if chemberta is None:
                    raise ValueError(f"mol_pooling={mol_pooling!r} requires --chemberta-cache")
                dim = int(chemberta["embeddings"][part].shape[1])
            else:
                cache = self.feature_caches.get(part)
                if cache is None:
                    raise KeyError(f"Sparse feature {part!r} was not found in any fingerprint manifest")
                dim = cache.dim(part)
            self.block_names.append(part)
            self.block_dims.append(dim)
        self.dim = sum(self.block_dims)
        if preload_sparse_features:
            for cache in self.sparse_caches:
                selected = [part for part in self.parts if part in cache.features]
                if selected:
                    cache.preload(selected)

    @property
    def fingerprint_cache_metadata(self) -> list[dict[str, Any]]:
        return [cache.metadata for cache in self.sparse_caches]

    @property
    def shape(self) -> tuple[int, int]:
        return self.size, self.dim

    def gather(self, indices: torch.Tensor) -> torch.Tensor:
        original_shape = tuple(indices.shape)
        flat = indices.reshape(-1).cpu()
        if self.dense is not None:
            gathered = self.dense[flat].float()
        else:
            if self.sparse is None or self.parts is None:
                raise RuntimeError("MoleculeEmbeddingStore was not initialized")
            pieces = []
            for part in self.parts:
                if part in ("mean", "cls"):
                    if self.chemberta is None:
                        raise RuntimeError("Dense molecule embeddings are unavailable")
                    pieces.append(self.chemberta["embeddings"][part][flat].float())
                else:
                    pieces.append(self.feature_caches[part].gather(part, flat))
            gathered = pieces[0] if len(pieces) == 1 else torch.cat(pieces, dim=1)
        return gathered.reshape(*original_shape, self.dim)

    def canonicalize_unique_indices(
        self,
        unique_indices: torch.Tensor,
        inverse: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Use backend-stable ordering for projection batches when available."""
        canonicalize = getattr(self.sparse, "canonicalize_unique_indices", None)
        if canonicalize is None:
            return unique_indices, inverse
        return canonicalize(unique_indices, inverse)


class MaterializedMoleculeEmbeddingStore:
    def __init__(
        self,
        source: MoleculeEmbeddingStore,
        required_indices: list[int],
        chunk_size: int,
    ) -> None:
        self.size = source.size
        self.dim = source.dim
        self.sparse = source.sparse
        self.sparse_caches = source.sparse_caches
        self.block_names = source.block_names
        self.block_dims = source.block_dims
        self.fingerprint_cache_metadata = source.fingerprint_cache_metadata
        self.global_to_local = torch.full((self.size,), -1, dtype=torch.int32)
        global_indices = torch.tensor(required_indices, dtype=torch.long)
        self.global_to_local[global_indices] = torch.arange(len(required_indices), dtype=torch.int32)
        self.dense = torch.empty((len(required_indices), self.dim), dtype=torch.float32)
        for start in tqdm(
            range(0, len(required_indices), chunk_size),
            desc="Materializing dataset molecule features",
        ):
            rows = global_indices[start : start + chunk_size]
            self.dense[start : start + len(rows)] = source.gather(rows)

    @property
    def shape(self) -> tuple[int, int]:
        return self.size, self.dim

    def gather(self, indices: torch.Tensor) -> torch.Tensor:
        original_shape = tuple(indices.shape)
        flat = indices.reshape(-1).cpu()
        local = self.global_to_local[flat].long()
        if bool((local < 0).any()):
            missing = flat[local < 0][:5].tolist()
            raise KeyError(f"Molecule rows were not materialized: {missing}")
        return self.dense[local].float().reshape(*original_shape, self.dim)


def materialize_for_datasets(
    source: MoleculeEmbeddingStore,
    datasets: list[ProjectionDataset],
    chunk_size: int,
) -> MaterializedMoleculeEmbeddingStore:
    required: set[int] = set()
    for dataset in datasets:
        for row in range(len(dataset)):
            item = dataset[row]
            required.update(int(index) for index in item["candidate_indices"])
    return MaterializedMoleculeEmbeddingStore(source, sorted(required), chunk_size)


def choose_device(name: str) -> torch.device:
    if name == "auto":
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")
    if name == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA was requested but torch.cuda.is_available() is false")
    return torch.device(name)


def normalized_candidate_pool(
    record: dict[str, Any],
    candidates: dict[str, list[str]],
    candidate_pool_limit: int,
) -> list[str]:
    gt = str(record["canonical_isomeric_smiles"])
    raw = str(record.get("raw_smiles") or gt)
    pool = candidates.get(raw) or candidates.get(gt) or []
    if candidate_pool_limit > 0:
        pool = pool[:candidate_pool_limit]
    normalized, _ = normalize_smiles_values(
        pool,
        mode="canonical_isomeric",
        drop_invalid=True,
        drop_multifragment=False,
        deduplicate=True,
    )
    if gt not in normalized:
        normalized.insert(0, gt)
    return normalized


def connectivity_identity(record: dict[str, Any], fallback_smiles: str) -> str:
    """Return the InChIKey connectivity layer used by formula-group protocols."""
    inchikey = str(record.get("inchikey") or "").strip()
    return inchikey.split("-", 1)[0] if inchikey else fallback_smiles


class ProjectionDataset(Dataset[dict[str, Any]]):
    def __init__(
        self,
        records: list[dict[str, Any]],
        dreams: torch.Tensor,
        candidates: dict[str, list[str]],
        smiles_to_index: dict[str, int],
        candidate_pool_limit: int,
        candidate_sidecar: dict[str, dict[str, Any]] | None = None,
        candidate_index_store: CandidateIndexStore | None = None,
        negative_exclusion: CandidateNegativeExclusion | None = None,
    ) -> None:
        if len(records) != int(dreams.shape[0]):
            raise ValueError(f"Record/embedding mismatch: {len(records)} records vs {tuple(dreams.shape)}")
        self.items: list[dict[str, Any]] = []
        self.candidate_index_store = candidate_index_store
        self.candidate_pool_limit = int(candidate_pool_limit)
        self.negative_exclusion = negative_exclusion
        if negative_exclusion is not None:
            if candidate_index_store is None:
                raise ValueError("Negative exclusion currently requires a candidate-index manifest")
            negative_exclusion.validate_candidate_store(candidate_index_store)
        stats = {
            "records_seen": len(records),
            "missing_gt_embedding": 0,
            "missing_sidecar": 0,
            "candidate_pool_too_small": 0,
            "usable_records": 0,
            "negative_exclusion_enabled": negative_exclusion is not None,
            "negative_candidates_seen": 0,
            "negative_candidates_excluded": 0,
            "candidate_rows_affected_by_exclusion": 0,
            "post_exclusion_pool_too_small": 0,
        }
        for row_idx, record in enumerate(records):
            if candidate_index_store is not None:
                identifier = record.get("identifier")
                candidate_row = (
                    candidate_index_store.row_for(str(identifier))
                    if identifier is not None
                    else None
                )
                if candidate_row is None:
                    stats["missing_sidecar"] += 1
                    continue
                raw_candidates = candidate_index_store.get_row(
                    candidate_row, candidate_pool_limit
                )
                if len(raw_candidates) < 2:
                    stats["candidate_pool_too_small"] += 1
                    continue
                if negative_exclusion is not None:
                    filtered_candidates, excluded = negative_exclusion.filter_candidates(
                        raw_candidates
                    )
                    stats["negative_candidates_seen"] += len(raw_candidates) - 1
                    stats["negative_candidates_excluded"] += excluded
                    stats["candidate_rows_affected_by_exclusion"] += int(excluded > 0)
                    if len(filtered_candidates) < 2:
                        stats["post_exclusion_pool_too_small"] += 1
                        continue
                gt = normalize_smiles(record.get("canonical_isomeric_smiles"), mode="canonical_isomeric")
                if gt is None:
                    stats["missing_gt_embedding"] += 1
                    continue
                self.items.append(
                    {
                        "row_idx": row_idx,
                        "identifier": identifier,
                        "spec": dreams[row_idx],
                        "gt": gt,
                        "gt_identity": connectivity_identity(record, gt),
                        "candidates": [],
                        "candidate_row": candidate_row,
                    }
                )
                continue
            sidecar_record = None
            if candidate_sidecar is not None:
                identifier = record.get("identifier")
                sidecar_record = candidate_sidecar.get(str(identifier)) if identifier is not None else None
                if sidecar_record is None:
                    stats["missing_sidecar"] += 1
                    continue
                gt = sidecar_record.get("normalized_gt_smiles")
            else:
                gt = normalize_smiles(record.get("canonical_isomeric_smiles"), mode="canonical_isomeric")
            if gt is None or gt not in smiles_to_index:
                stats["missing_gt_embedding"] += 1
                continue
            if sidecar_record is not None:
                pool = list(sidecar_record.get("normalized_candidates") or [])
                if candidate_pool_limit > 0:
                    pool = pool[:candidate_pool_limit]
                if gt not in pool:
                    pool.insert(0, gt)
                elif pool[0] != gt:
                    pool = [gt] + [smiles for smiles in pool if smiles != gt]
            else:
                pool = normalized_candidate_pool(record, candidates, candidate_pool_limit)
            pool = [smiles for smiles in pool if smiles in smiles_to_index]
            if gt not in pool:
                pool.insert(0, gt)
            negatives = [smiles for smiles in pool if smiles != gt]
            if not negatives:
                stats["candidate_pool_too_small"] += 1
                continue
            self.items.append(
                {
                    "row_idx": row_idx,
                    "identifier": record.get("identifier"),
                    "spec": dreams[row_idx],
                    "gt": gt,
                    "gt_identity": connectivity_identity(record, gt),
                    "candidates": [gt] + negatives,
                    "candidate_indices": [smiles_to_index[smiles] for smiles in [gt] + negatives],
                }
            )
        stats["usable_records"] = len(self.items)
        stats["connectivity_groups"] = len(
            {str(item["gt_identity"]) for item in self.items}
        )
        self.stats = stats
        if stats["post_exclusion_pool_too_small"]:
            raise ValueError(
                "Negative exclusion left one or more training rows without a negative: "
                f"{stats['post_exclusion_pool_too_small']}"
            )

    def __len__(self) -> int:
        return len(self.items)

    def __getitem__(self, index: int) -> dict[str, Any]:
        item = self.items[index]
        if self.candidate_index_store is None:
            return item
        hydrated = dict(item)
        candidate_indices = self.candidate_index_store.get_row(
            int(item["candidate_row"]), self.candidate_pool_limit
        )
        if self.negative_exclusion is not None:
            candidate_indices, _ = self.negative_exclusion.filter_candidates(candidate_indices)
        hydrated["candidate_indices"] = candidate_indices
        return hydrated


