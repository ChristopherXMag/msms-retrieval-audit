def molecule_head_metadata(
    model: ProjectionModel,
    state_dict: Mapping[str, torch.Tensor] | None = None,
) -> dict[str, Any]:
    metadata: dict[str, Any] = {
        "type": model.mol_head_type,
        "block_names": list(model.mol_block_names),
        "block_dims": list(model.mol_block_dims),
        "normalization": model.mol_block_normalization,
        "branch_dims": list(model.mol_branch_dims),
        "fusion_hidden_dim": model.mol_fusion_hidden_dim,
        "parameters": count_parameters(model.mol_head),
    }
    if isinstance(model.mol_head, GatedBlockMoleculeHead):
        logits = model.mol_head.gate_logits.detach().cpu()
        if state_dict is not None and "mol_head.gate_logits" in state_dict:
            logits = state_dict["mol_head.gate_logits"].detach().cpu()
        gates = len(model.mol_block_dims) * torch.softmax(logits.float(), dim=0)
        metadata["gate_logits"] = [float(value) for value in logits]
        metadata["gate_values"] = {
            name: float(value)
            for name, value in zip(model.mol_block_names, gates, strict=True)
        }
    else:
        metadata["gate_values"] = None
    return metadata


def sample_candidate_indices(
    item: dict[str, Any],
    smiles_to_index: dict[str, int],
    candidate_negatives: int,
    rng: random.Random,
    negative_sampling: str,
    hard_negative_fraction: float,
) -> list[int]:
    del smiles_to_index
    gt_index = item["candidate_indices"][0]
    negative_indices = list(item["candidate_indices"][1:])
    if candidate_negatives <= 0 or len(negative_indices) <= candidate_negatives:
        return [gt_index] + negative_indices

    if negative_sampling == "random":
        chosen_negatives = rng.sample(negative_indices, candidate_negatives)
    elif negative_sampling == "morgan_tanimoto":
        hard_order = item.get("morgan_hard_negative_indices")
        if hard_order is None:
            raise ValueError("Morgan hard negatives were requested but were not precomputed")
        chosen_negatives = list(hard_order[:candidate_negatives])
    elif negative_sampling == "morgan_tanimoto_hybrid":
        hard_order = item.get("morgan_hard_negative_indices")
        if hard_order is None:
            raise ValueError("Morgan hard negatives were requested but were not precomputed")
        chosen_negatives = choose_hard_random_hybrid(
            hard_order,
            negative_indices,
            candidate_negatives,
            hard_negative_fraction,
            rng,
        )
    elif negative_sampling == "structure_hard":
        hard_order = item.get("structure_hard_negative_indices")
        if hard_order is None:
            raise ValueError("Structure hard negatives were requested but were not precomputed")
        chosen_negatives = list(hard_order[:candidate_negatives])
    elif negative_sampling == "structure_hard_hybrid":
        hard_order = item.get("structure_hard_negative_indices")
        if hard_order is None:
            raise ValueError("Structure hard negatives were requested but were not precomputed")
        chosen_negatives = choose_hard_random_hybrid(
            hard_order,
            negative_indices,
            candidate_negatives,
            hard_negative_fraction,
            rng,
        )
    else:
        raise ValueError(f"Unsupported negative_sampling: {negative_sampling}")
    return [gt_index] + chosen_negatives


def choose_hard_random_hybrid(
    hard_order: list[int],
    negative_indices: list[int],
    candidate_negatives: int,
    hard_negative_fraction: float,
    rng: random.Random,
) -> list[int]:
    hard_count = int(round(candidate_negatives * hard_negative_fraction))
    hard_count = max(0, min(candidate_negatives, hard_count))
    hard_part = list(hard_order[:hard_count])
    hard_set = set(hard_part)
    remaining = [idx for idx in negative_indices if idx not in hard_set]
    random_count = candidate_negatives - len(hard_part)
    if len(remaining) > random_count:
        random_part = rng.sample(remaining, random_count)
    else:
        random_part = remaining
    chosen_negatives = hard_part + random_part
    if len(chosen_negatives) < candidate_negatives:
        chosen_set = set(chosen_negatives)
        for idx in hard_order:
            if idx not in chosen_set:
                chosen_negatives.append(idx)
                chosen_set.add(idx)
                if len(chosen_negatives) == candidate_negatives:
                    break
    return chosen_negatives


@torch.inference_mode()
def add_morgan_hard_negative_order(dataset: ProjectionDataset, morgan_embeddings: torch.Tensor) -> None:
    if morgan_embeddings.ndim != 2:
        raise ValueError(f"Expected 2D Morgan embeddings, got {tuple(morgan_embeddings.shape)}")
    for item in tqdm(dataset.items, desc="Precomputing Morgan hard negatives"):
        gt_index = int(item["candidate_indices"][0])
        negative_indices = list(item["candidate_indices"][1:])
        if not negative_indices:
            item["morgan_hard_negative_indices"] = []
            continue
        gt_fp = morgan_embeddings[gt_index].float()
        neg_tensor = torch.tensor(negative_indices, dtype=torch.long)
        neg_fp = morgan_embeddings[neg_tensor].float()
        intersection = torch.matmul(neg_fp, gt_fp)
        union = neg_fp.sum(dim=1) + gt_fp.sum() - intersection
        tanimoto = torch.where(union > 0, intersection / union.clamp_min(1.0), torch.zeros_like(union))
        order = torch.argsort(tanimoto, descending=True)
        item["morgan_hard_negative_indices"] = [negative_indices[int(idx)] for idx in order.tolist()]


def molecule_formula_and_scaffold(smiles: str) -> tuple[str | None, str | None]:
    if Chem is None or rdMolDescriptors is None or MurckoScaffold is None:
        raise RuntimeError("RDKit is required for structure_hard negative sampling")
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return None, None
    formula = rdMolDescriptors.CalcMolFormula(mol)
    scaffold = MurckoScaffold.MurckoScaffoldSmiles(mol=mol, includeChirality=False)
    return formula or None, scaffold or None


@torch.inference_mode()
def add_structure_hard_negative_order(dataset: ProjectionDataset, morgan_embeddings: torch.Tensor) -> None:
    if morgan_embeddings.ndim != 2:
        raise ValueError(f"Expected 2D Morgan embeddings, got {tuple(morgan_embeddings.shape)}")
    descriptor_cache: dict[str, tuple[str | None, str | None]] = {}
    total_formula_matches = 0
    total_scaffold_matches = 0
    total_rows = 0
    for item in tqdm(dataset.items, desc="Precomputing structure hard negatives"):
        gt_index = int(item["candidate_indices"][0])
        negative_indices = list(item["candidate_indices"][1:])
        negative_smiles = [str(smiles) for smiles in item["candidates"][1:]]
        if len(negative_indices) != len(negative_smiles):
            raise ValueError("Candidate index/SMILES length mismatch while building structure hard negatives")
        if not negative_indices:
            item["structure_hard_negative_indices"] = []
            continue

        gt_smiles = str(item["candidates"][0])
        if gt_smiles not in descriptor_cache:
            descriptor_cache[gt_smiles] = molecule_formula_and_scaffold(gt_smiles)
        gt_formula, gt_scaffold = descriptor_cache[gt_smiles]

        gt_fp = morgan_embeddings[gt_index].float()
        neg_tensor = torch.tensor(negative_indices, dtype=torch.long)
        neg_fp = morgan_embeddings[neg_tensor].float()
        intersection = torch.matmul(neg_fp, gt_fp)
        union = neg_fp.sum(dim=1) + gt_fp.sum() - intersection
        tanimoto = torch.where(union > 0, intersection / union.clamp_min(1.0), torch.zeros_like(union))

        scored: list[tuple[float, int]] = []
        row_formula_matches = 0
        row_scaffold_matches = 0
        for pos, (candidate_index, smiles) in enumerate(zip(negative_indices, negative_smiles, strict=True)):
            if smiles not in descriptor_cache:
                descriptor_cache[smiles] = molecule_formula_and_scaffold(smiles)
            formula, scaffold = descriptor_cache[smiles]
            same_formula = gt_formula is not None and formula == gt_formula
            same_scaffold = gt_scaffold is not None and scaffold == gt_scaffold
            row_formula_matches += int(same_formula)
            row_scaffold_matches += int(same_scaffold)
            score = float(tanimoto[pos].cpu())
            if same_formula:
                score += 2.0
            if same_scaffold:
                score += 1.0
            scored.append((score, int(candidate_index)))
        scored.sort(key=lambda pair: pair[0], reverse=True)
        item["structure_hard_negative_indices"] = [candidate_index for _, candidate_index in scored]
        total_formula_matches += row_formula_matches
        total_scaffold_matches += row_scaffold_matches
        total_rows += 1

    dataset.stats["structure_hard_rows"] = total_rows
    dataset.stats["structure_hard_formula_matches_per_row"] = round(total_formula_matches / max(total_rows, 1), 4)
    dataset.stats["structure_hard_scaffold_matches_per_row"] = round(total_scaffold_matches / max(total_rows, 1), 4)


def append_inbatch_gt_indices(
    batch: list[dict[str, Any]],
    base_indices: list[list[int]],
    base_masks: list[list[bool]],
    smiles_to_index: dict[str, int],
) -> tuple[list[list[int]], list[list[bool]], dict[str, float]]:
    gt_values = [str(item["gt"]) for item in batch]
    identity_values = [str(item.get("gt_identity") or item["gt"]) for item in batch]
    gt_indices = [smiles_to_index[gt] for gt in gt_values]

    appended_indices: list[list[int]] = []
    appended_masks: list[list[bool]] = []
    valid_extra = 0
    masked_extra = 0
    for item, indices, mask in zip(batch, base_indices, base_masks, strict=True):
        row_gt = str(item["gt"])
        row_identity = str(item.get("gt_identity") or row_gt)
        row_extra_mask = [
            (gt != row_gt) and (identity != row_identity)
            for gt, identity in zip(gt_values, identity_values, strict=True)
        ]
        valid_extra += sum(row_extra_mask)
        masked_extra += len(row_extra_mask) - sum(row_extra_mask)
        appended_indices.append(indices + gt_indices)
        appended_masks.append(mask + row_extra_mask)

    denom = max(len(batch), 1)
    return appended_indices, appended_masks, {
        "inbatch_gt_valid_per_query": valid_extra / denom,
        "inbatch_gt_masked_per_query": masked_extra / denom,
    }


def train_one_epoch(
    model: ProjectionModel,
    loader: DataLoader,
    mol_store: MoleculeEmbeddingStore,
    smiles_to_index: dict[str, int],
    optimizer: torch.optim.Optimizer,
    device: torch.device,
    candidate_negatives: int,
    loss_mode: str,
    negative_sampling: str,
    hard_negative_fraction: float,
    seed: int,
    counterfactual_weight: float = 0.0,
    counterfactual_margin: float = 1.0,
) -> dict[str, float]:
    model.train()
    rng = random.Random(seed)
    total_loss = 0.0
    total_items = 0
    total_valid_extra = 0.0
    total_masked_extra = 0.0
    total_candidate_ce = 0.0
    total_counterfactual_loss = 0.0
    total_counterfactual_delta = 0.0
    total_counterfactual_real_margin = 0.0
    total_counterfactual_wrong_margin = 0.0
    total_counterfactual_pass = 0.0
    total_counterfactual_pairs = 0
    for batch in tqdm(loader, desc="Training projection heads"):
        specs = torch.stack([item["spec"] for item in batch], dim=0).to(device)
        candidate_indices = [
            sample_candidate_indices(
                item,
                smiles_to_index,
                candidate_negatives,
                rng,
                negative_sampling,
                hard_negative_fraction,
            )
            for item in batch
        ]
        mask = [[True] * len(indices) for indices in candidate_indices]
        if loss_mode == "candidate_ce_inbatch_gt":
            candidate_indices, mask, inbatch_stats = append_inbatch_gt_indices(
                batch,
                candidate_indices,
                mask,
                smiles_to_index,
            )
            total_valid_extra += inbatch_stats["inbatch_gt_valid_per_query"] * len(batch)
            total_masked_extra += inbatch_stats["inbatch_gt_masked_per_query"] * len(batch)
        elif loss_mode not in {"candidate_ce", "candidate_ce_counterfactual"}:
            raise ValueError(f"Unsupported loss_mode: {loss_mode}")

        max_len = max(len(indices) for indices in candidate_indices)
        padded_indices = []
        padded_mask = []
        for indices in candidate_indices:
            padded = indices + [indices[0]] * (max_len - len(indices))
            padded_indices.append(padded)
        for row_mask in mask:
            padded_mask.append(row_mask + [False] * (max_len - len(row_mask)))
        index_tensor = torch.tensor(padded_indices, dtype=torch.long)
        mol = mol_store.gather(index_tensor).to(device)
        mask_tensor = torch.tensor(padded_mask, dtype=torch.bool, device=device)

        spec_proj = model.project_spec(specs)
        mol_proj = model.project_mol(mol.reshape(-1, mol.shape[-1])).reshape(len(batch), max_len, -1)
        logits = torch.einsum("bd,bcd->bc", spec_proj, mol_proj) / model.temperature()
        logits = logits.masked_fill(~mask_tensor, float("-inf"))
        labels = torch.zeros(len(batch), dtype=torch.long, device=device)
        candidate_ce = F.cross_entropy(logits, labels)
        loss = candidate_ce
        counterfactual_loss: torch.Tensor | None = None
        if loss_mode == "candidate_ce_counterfactual":
            eligible = [
                index for index, item in enumerate(batch) if item.get("counterfactual_spec") is not None
            ]
            if eligible:
                eligible_tensor = torch.tensor(eligible, dtype=torch.long, device=device)
                wrong_specs = torch.stack(
                    [batch[index]["counterfactual_spec"] for index in eligible], dim=0
                ).to(device)
                wrong_spec_proj = model.project_spec(wrong_specs)
                eligible_mol_proj = mol_proj[eligible_tensor]
                wrong_logits = torch.einsum(
                    "bd,bcd->bc", wrong_spec_proj, eligible_mol_proj
                ) / model.temperature()
                eligible_mask = mask_tensor[eligible_tensor]
                wrong_logits = wrong_logits.masked_fill(~eligible_mask, float("-inf"))
                real_logits = logits[eligible_tensor]
                decoy_scores = real_logits[:, 1:].clone()
                decoy_scores = decoy_scores.masked_fill(~eligible_mask[:, 1:], float("-inf"))
                hard_decoy = torch.argmax(decoy_scores, dim=1) + 1
                real_decoy = real_logits.gather(1, hard_decoy[:, None]).squeeze(1)
                wrong_decoy = wrong_logits.gather(1, hard_decoy[:, None]).squeeze(1)
                real_margin = real_logits[:, 0] - real_decoy
                wrong_margin = wrong_logits[:, 0] - wrong_decoy
                spectral_delta = real_margin - wrong_margin
                counterfactual_loss = F.softplus(counterfactual_margin - spectral_delta).mean()
                loss = loss + counterfactual_weight * counterfactual_loss

                count = len(eligible)
                total_counterfactual_loss += float(counterfactual_loss.detach().cpu()) * count
                total_counterfactual_delta += float(spectral_delta.detach().sum().cpu())
                total_counterfactual_real_margin += float(real_margin.detach().sum().cpu())
                total_counterfactual_wrong_margin += float(wrong_margin.detach().sum().cpu())
                total_counterfactual_pass += float(
                    (spectral_delta.detach() >= counterfactual_margin).sum().cpu()
                )
                total_counterfactual_pairs += count

        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()

        total_loss += float(loss.detach().cpu()) * len(batch)
        total_candidate_ce += float(candidate_ce.detach().cpu()) * len(batch)
        total_items += len(batch)
    metrics = {
        "loss": total_loss / max(total_items, 1),
        "candidate_ce": total_candidate_ce / max(total_items, 1),
        "temperature": float(model.temperature().detach().cpu()),
    }
    if loss_mode == "candidate_ce_inbatch_gt":
        metrics["inbatch_gt_valid_per_query"] = total_valid_extra / max(total_items, 1)
        metrics["inbatch_gt_masked_per_query"] = total_masked_extra / max(total_items, 1)
    if loss_mode == "candidate_ce_counterfactual":
        metrics.update(
            {
                "counterfactual_pairs": float(total_counterfactual_pairs),
                "counterfactual_pair_fraction": total_counterfactual_pairs / max(total_items, 1),
                "counterfactual_loss": total_counterfactual_loss
                / max(total_counterfactual_pairs, 1),
                "counterfactual_spectral_delta": total_counterfactual_delta
                / max(total_counterfactual_pairs, 1),
                "counterfactual_real_margin": total_counterfactual_real_margin
                / max(total_counterfactual_pairs, 1),
                "counterfactual_wrong_margin": total_counterfactual_wrong_margin
                / max(total_counterfactual_pairs, 1),
                "counterfactual_margin_pass_rate": total_counterfactual_pass
                / max(total_counterfactual_pairs, 1),
                "counterfactual_weight": counterfactual_weight,
                "counterfactual_target_margin": counterfactual_margin,
            }
        )
    return metrics


@torch.inference_mode()
def evaluate(
    model: ProjectionModel,
    dataset: ProjectionDataset,
    mol_store: MoleculeEmbeddingStore,
    smiles_to_index: dict[str, int],
    device: torch.device,
    batch_size: int,
    include_ranks: bool = False,
) -> dict[str, Any]:
    model.eval()
    ranks: list[int] = []
    for start in tqdm(range(0, len(dataset), batch_size), desc="Evaluating candidate ranks"):
        items = [dataset[row] for row in range(start, min(start + batch_size, len(dataset)))]
        specs = torch.stack([item["spec"] for item in items], dim=0).to(device)
        candidate_indices = [item["candidate_indices"] for item in items]
        max_len = max(len(indices) for indices in candidate_indices)
        padded_indices = []
        mask = []
        for indices in candidate_indices:
            padded = indices + [indices[0]] * (max_len - len(indices))
            padded_indices.append(padded)
            mask.append([True] * len(indices) + [False] * (max_len - len(indices)))
        index_tensor = torch.tensor(padded_indices, dtype=torch.long)
        mask_tensor = torch.tensor(mask, dtype=torch.bool, device=device)
        spec_proj = model.project_spec(specs)
        unique_indices, inverse = torch.unique(index_tensor.reshape(-1), sorted=True, return_inverse=True)
        unique_indices, inverse = mol_store.canonicalize_unique_indices(unique_indices, inverse)
        unique_mol = mol_store.gather(unique_indices).to(device)
        unique_proj = model.project_mol(unique_mol)
        mol_proj = unique_proj[inverse.to(device)].reshape(len(items), max_len, -1)
        scores = torch.einsum("bd,bcd->bc", spec_proj, mol_proj) / model.temperature()
        scores = scores.masked_fill(~mask_tensor, float("-inf"))
        order = torch.argsort(scores, dim=1, descending=True)
        batch_ranks = (order == 0).nonzero(as_tuple=False)[:, 1] + 1
        ranks.extend(int(rank) for rank in batch_ranks.cpu())
    if not ranks:
        return {
            "valid_queries": 0,
            "recall@1": 0.0,
            "recall@5": 0.0,
            "recall@20": 0.0,
            "recall@50": 0.0,
            "recall@100": 0.0,
            "mrr": 0.0,
        }
    values = torch.tensor(ranks, dtype=torch.float32)
    metrics: dict[str, Any] = {
        "valid_queries": len(ranks),
        "recall@1": round(float((values <= 1).float().mean()) * 100, 4),
        "recall@5": round(float((values <= 5).float().mean()) * 100, 4),
        "recall@20": round(float((values <= 20).float().mean()) * 100, 4),
        "recall@50": round(float((values <= 50).float().mean()) * 100, 4),
        "recall@100": round(float((values <= 100).float().mean()) * 100, 4),
        "mrr": round(float((1.0 / values).mean()) * 100, 4),
        "median_rank": round(float(values.median()), 4),
        "mean_rank": round(float(values.mean()), 4),
    }
    if include_ranks:
        metrics["ranks"] = ranks
    return metrics


def main() -> None:
    args = parse_args()
    torch.manual_seed(args.seed)
    random.seed(args.seed)
    device = choose_device(args.device)

    train_records = load_jsonl(args.train_metadata)
    val_records = load_jsonl(args.val_metadata)
    train_dreams = load_dreams(args.train_dreams)
    val_dreams = load_dreams(args.val_dreams)
    if args.train_limit > 0:
        train_records = train_records[: args.train_limit]
        train_dreams = train_dreams[: args.train_limit]
    if args.val_limit > 0:
        val_records = val_records[: args.val_limit]
        val_dreams = val_dreams[: args.val_limit]
    chemberta = (
        torch.load(str(args.chemberta_cache), map_location="cpu", weights_only=False, mmap=True)
        if args.chemberta_cache is not None
        else None
    )
    candidate_index_store = (
        CandidateIndexStore(args.candidate_index_manifest)
        if args.candidate_index_manifest is not None
        else None
    )
    if candidate_index_store is not None and args.candidate_sidecar is not None:
        raise ValueError("Use only one of --candidate-index-manifest and --candidate-sidecar")
    if candidate_index_store is not None and args.loss_mode not in {
        "candidate_ce",
        "candidate_ce_counterfactual",
    }:
        raise ValueError(
            "Compact candidate indices currently support candidate_ce and "
            "candidate_ce_counterfactual only"
        )
    sidecar_path = args.candidate_sidecar
    if sidecar_path is None and candidate_index_store is None and chemberta is not None:
        metadata_sidecar = chemberta.get("metadata", {}).get("candidate_sidecar")
        if metadata_sidecar:
            path = Path(metadata_sidecar)
            if path.exists():
                sidecar_path = path
    candidate_sidecar = load_candidate_sidecar(sidecar_path) if sidecar_path is not None else None
    if candidate_sidecar is None and candidate_index_store is None:
        with args.candidates_json.open(encoding="utf-8") as handle:
            candidates = json.load(handle)
    else:
        candidates = {}
    smiles_to_index = chemberta["smiles_to_index"] if chemberta is not None else {}
    mol_store = MoleculeEmbeddingStore(
        chemberta,
        args.mol_pooling,
        args.fingerprint_cache,
        additional_fingerprint_caches=args.additional_fingerprint_cache,
        preload_sparse_features=args.preload_sparse_features,
        mol_blocks=args.mol_blocks,
    )
    if candidate_index_store is not None:
        if candidate_index_store.molecule_rows != mol_store.size:
            raise ValueError(
                "Candidate-index and molecule-feature row counts differ: "
                f"{candidate_index_store.molecule_rows} != {mol_store.size}"
            )
        if (
            candidate_index_store.molecule_smiles_sha256
            and mol_store.smiles_sha256
            and candidate_index_store.molecule_smiles_sha256 != mol_store.smiles_sha256
        ):
            raise ValueError("Candidate-index and molecule-feature SMILES digests differ")

    negative_exclusion = (
        CandidateNegativeExclusion(args.negative_exclusion_manifest)
        if args.negative_exclusion_manifest is not None
        else None
    )
    if negative_exclusion is not None:
        if candidate_index_store is None:
            raise ValueError("--negative-exclusion-manifest requires --candidate-index-manifest")
        negative_exclusion.validate_candidate_store(candidate_index_store)
    train_dataset = ProjectionDataset(
        train_records,
        train_dreams,
        candidates,
        smiles_to_index,
        args.candidate_pool_limit,
        candidate_sidecar=candidate_sidecar,
        candidate_index_store=candidate_index_store,
        negative_exclusion=negative_exclusion,
    )
    val_dataset = ProjectionDataset(
        val_records,
        val_dreams,
        candidates,
        smiles_to_index,
        args.candidate_pool_limit,
        candidate_sidecar=candidate_sidecar,
        candidate_index_store=candidate_index_store,
    )
    if len(train_dataset) == 0 or len(val_dataset) == 0:
        raise ValueError(f"Empty train/val dataset: train={train_dataset.stats}, val={val_dataset.stats}")
    counterfactual_assignment_audit: dict[str, Any] | None = None
    if args.loss_mode == "candidate_ce_counterfactual":
        if args.counterfactual_weight <= 0:
            raise ValueError("--counterfactual-weight must be positive for counterfactual training")
        if args.counterfactual_margin < 0:
            raise ValueError("--counterfactual-margin must be non-negative")
        assignment, counterfactual_assignment_audit = build_counterfactual_donor_assignment(
            train_records,
            mass_round_decimals=args.counterfactual_mass_round_decimals,
            seed=args.counterfactual_seed,
            match_instrument=True,
            match_ce_known=True,
            jitter=args.counterfactual_assignment_jitter,
        )
        attached = 0
        for item in train_dataset.items:
            donor = assignment.get(int(item["row_idx"]))
            if donor is not None:
                item["counterfactual_spec"] = train_dreams[donor]
                item["counterfactual_donor_row"] = donor
                attached += 1
        counterfactual_assignment_audit["dataset_recipients_attached"] = attached
        counterfactual_assignment_audit["dataset_recipient_fraction"] = attached / max(
            len(train_dataset), 1
        )
        if attached == 0:
            raise ValueError("Counterfactual pairing produced no usable training recipients")
    if args.negative_sampling.startswith("morgan_tanimoto"):
        if chemberta is None:
            raise ValueError("Morgan hard negatives require --chemberta-cache")
        morgan_embeddings = chemberta.get("embeddings", {}).get("morgan")
        if morgan_embeddings is None:
            raise ValueError("--negative-sampling morgan_* requires embeddings['morgan'] in --chemberta-cache")
        add_morgan_hard_negative_order(train_dataset, morgan_embeddings)
    elif args.negative_sampling.startswith("structure_hard"):
        if chemberta is None:
            raise ValueError("Structure hard negatives require --chemberta-cache")
        morgan_embeddings = chemberta.get("embeddings", {}).get("morgan")
        if morgan_embeddings is None:
            raise ValueError("--negative-sampling structure_hard* requires embeddings['morgan'] in --chemberta-cache")
        add_structure_hard_negative_order(train_dataset, morgan_embeddings)
    if args.materialize_dataset_features:
        mol_store = materialize_for_datasets(
            mol_store,
            [train_dataset, val_dataset],
            args.materialize_chunk_size,
        )

    resume_payload: dict[str, Any] | None = None
    effective_model_config = dict(vars(args))
    if args.resume_checkpoint is not None:
        resume_payload = torch.load(args.resume_checkpoint, map_location="cpu", weights_only=False)
        checkpoint_config = checkpoint_model_config(resume_payload)
        for key in (
            "hidden_dim",
            "proj_dim",
            "dropout",
            "temperature",
            "head_type",
            "mol_block_normalization",
            "mol_head_type",
            "mol_branch_dims",
            "mol_fusion_hidden_dim",
        ):
            if key in checkpoint_config:
                effective_model_config[key] = checkpoint_config[key]

    model = build_projection_model(
        spec_dim=int(train_dreams.shape[1]),
        mol_dim=mol_store.dim,
        mol_block_dims=mol_store.block_dims,
        mol_block_names=mol_store.block_names,
        config=effective_model_config,
    ).to(device)
    if args.freeze_temperature:
        model.log_temperature.requires_grad_(False)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)
    epoch_sampler: Sampler[int] | None = None
    if args.train_sampling == "molecule_balanced":
        epoch_sampler = MoleculeBalancedEpochSampler(train_dataset, args.seed)
    elif args.train_sampling == "sqrt_count":
        epoch_sampler = SqrtCountEpochSampler(train_dataset, args.seed)
    loader = DataLoader(
        train_dataset,
        batch_size=args.batch_size,
        shuffle=epoch_sampler is None,
        sampler=epoch_sampler,
        collate_fn=collate_records,
        drop_last=False,
        num_workers=0,
    )

    history: list[dict[str, Any]] = []
    started = time.time()
    start_epoch = 0
    if args.resume_checkpoint is not None:
        if resume_payload is None:
            raise RuntimeError("Resume checkpoint was not loaded")
        checkpoint_payload = resume_payload
        state = checkpoint_payload.get("model_state_dict") or checkpoint_payload.get("last_model_state_dict")
        if state is None:
            raise ValueError(f"No model_state_dict found in resume checkpoint: {args.resume_checkpoint}")
        model.load_state_dict(state)
        optimizer_state = checkpoint_payload.get("optimizer_state_dict")
        if optimizer_state is not None:
            optimizer.load_state_dict(optimizer_state)
        history = list(checkpoint_payload.get("history") or [])
        start_epoch = int(checkpoint_payload.get("last_epoch") or (history[-1]["epoch"] if history else 0))
        best_epoch = int(checkpoint_payload.get("best_epoch", 0))
        best_val = checkpoint_payload.get("best_val")
        best_state = checkpoint_payload.get("best_model_state_dict")
        if best_val is None or best_state is None:
            best_val = evaluate(model, val_dataset, mol_store, smiles_to_index, device, args.eval_batch_size)
            best_epoch = start_epoch
            best_state = {key: value.detach().cpu().clone() for key, value in model.state_dict().items()}
        print(
            json.dumps(
                {
                    "resumed_from": str(args.resume_checkpoint),
                    "start_epoch": start_epoch,
                    "best_epoch": best_epoch,
                    "best_val": best_val,
                },
                indent=2,
                sort_keys=True,
            )
        )
    else:
        epoch0_val = evaluate(model, val_dataset, mol_store, smiles_to_index, device, args.eval_batch_size)
        history.append(
            {
                "epoch": 0,
                "val": epoch0_val,
                "molecule_gate_values": molecule_head_metadata(model)["gate_values"],
            }
        )
        print(json.dumps(history[-1], indent=2, sort_keys=True))
        best_epoch = 0
        best_val = epoch0_val
        best_state = {key: value.detach().cpu().clone() for key, value in model.state_dict().items()}

    if start_epoch >= args.epochs:
        print(
            json.dumps(
                {"message": "resume checkpoint already reached requested --epochs", "start_epoch": start_epoch},
                indent=2,
                sort_keys=True,
            )
        )

    for epoch in range(start_epoch + 1, args.epochs + 1):
        if epoch_sampler is not None:
            epoch_sampler.set_epoch(epoch)
        train_metrics = train_one_epoch(
            model,
            loader,
            mol_store,
            smiles_to_index,
            optimizer,
            device,
            args.candidate_negatives,
            args.loss_mode,
            args.negative_sampling,
            args.hard_negative_fraction,
            args.seed + epoch,
            args.counterfactual_weight,
            args.counterfactual_margin,
        )
        val_metrics = evaluate(model, val_dataset, mol_store, smiles_to_index, device, args.eval_batch_size)
        row = {
            "epoch": epoch,
            "train": train_metrics,
            "val": val_metrics,
            "molecule_gate_values": molecule_head_metadata(model)["gate_values"],
        }
        history.append(row)
        if (
            float(val_metrics["mrr"]),
            float(val_metrics["recall@1"]),
            float(val_metrics["recall@20"]),
        ) > (
            float(best_val["mrr"]),
            float(best_val["recall@1"]),
            float(best_val["recall@20"]),
        ):
            best_epoch = epoch
