def parse_positive_int_csv(value: str) -> list[int]:
    try:
        parsed = [int(item.strip()) for item in value.split(",")]
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"Expected comma-separated integers, got {value!r}") from exc
    if not parsed or any(item <= 0 for item in parsed):
        raise argparse.ArgumentTypeError(f"Dimensions must be positive, got {value!r}")
    return parsed


def parse_string_csv(value: str) -> list[str]:
    parsed = [item.strip() for item in value.split(",") if item.strip()]
    if not parsed:
        raise argparse.ArgumentTypeError("Expected at least one comma-separated value")
    if len(set(parsed)) != len(parsed):
        raise argparse.ArgumentTypeError(f"Duplicate values are not allowed: {value!r}")
    return parsed


