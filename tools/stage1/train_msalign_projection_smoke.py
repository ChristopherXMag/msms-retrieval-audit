class MoleculeBalancedEpochSampler(Sampler[int]):
    """Select one rotating spectrum view per GT molecule for each epoch."""

    def __init__(self, dataset: ProjectionDataset, seed: int) -> None:
        self.seed = int(seed)
        self.epoch = 1
        groups: dict[str, list[int]] = {}
        for index, item in enumerate(dataset.items):
            groups.setdefault(str(item["gt_identity"]), []).append(index)
        self.groups = []
        for identity in sorted(groups):
            rows = list(groups[identity])
            identity_seed = int.from_bytes(
                hashlib.sha256(identity.encode("utf-8")).digest()[:8], "little"
            )
            random.Random(self.seed ^ identity_seed).shuffle(rows)
            self.groups.append(rows)
        if not self.groups:
            raise ValueError("Molecule-balanced sampling received no molecule groups")

    def set_epoch(self, epoch: int) -> None:
        self.epoch = int(epoch)

    def __len__(self) -> int:
        return len(self.groups)

    def __iter__(self):
        selected = [rows[(self.epoch - 1) % len(rows)] for rows in self.groups]
        random.Random(self.seed + 1_000_003 * self.epoch).shuffle(selected)
        return iter(selected)


class SqrtCountEpochSampler(Sampler[int]):
    """Select round(sqrt(n)) rotating spectra per GT molecule each epoch.

    Molecule exposure interpolates between molecule_balanced (k=1) and
    row_shuffle (k=n). k is at least 1 and at most n.
    """

    def __init__(self, dataset: ProjectionDataset, seed: int, exponent: float = 0.5) -> None:
        if exponent <= 0:
            raise ValueError("sqrt_count exponent must be positive")
        self.seed = int(seed)
        self.exponent = float(exponent)
        self.epoch = 1
        groups: dict[str, list[int]] = {}
        for index, item in enumerate(dataset.items):
            groups.setdefault(str(item["gt_identity"]), []).append(index)
        self.groups: list[tuple[list[int], int]] = []
        for identity in sorted(groups):
            rows = list(groups[identity])
            identity_seed = int.from_bytes(
                hashlib.sha256(identity.encode("utf-8")).digest()[:8], "little"
            )
            random.Random(self.seed ^ identity_seed).shuffle(rows)
            k = max(1, min(len(rows), int(round(len(rows) ** self.exponent))))
            self.groups.append((rows, k))
        if not self.groups:
            raise ValueError("sqrt_count sampling received no molecule groups")
        self._length = sum(k for _, k in self.groups)

    def set_epoch(self, epoch: int) -> None:
        self.epoch = int(epoch)

    def __len__(self) -> int:
        return self._length

    def quota(self, n_spectra: int) -> int:
        return max(1, min(n_spectra, int(round(n_spectra ** self.exponent))))

    def __iter__(self):
        selected: list[int] = []
        for rows, k in self.groups:
            n = len(rows)
            start = ((self.epoch - 1) * k) % n
            if k == n:
                chosen = list(rows)
            elif start + k <= n:
                chosen = rows[start : start + k]
            else:
                chosen = rows[start:] + rows[: k - (n - start)]
            selected.extend(chosen)
        random.Random(self.seed + 1_000_003 * self.epoch).shuffle(selected)
        return iter(selected)


class ProjectionHead(nn.Module):
    def __init__(self, in_dim: int, hidden_dim: int, out_dim: int, dropout: float, head_type: str) -> None:
        super().__init__()
        self.head_type = head_type
        if head_type == "linear":
            layers: list[nn.Module] = [
                nn.LayerNorm(in_dim),
                nn.Linear(in_dim, out_dim),
                nn.LayerNorm(out_dim),
            ]
        elif head_type == "mlp":
            layers: list[nn.Module] = [
                nn.LayerNorm(in_dim),
                nn.Linear(in_dim, hidden_dim),
                nn.GELU(),
                nn.Dropout(dropout),
                nn.Linear(hidden_dim, out_dim),
                nn.LayerNorm(out_dim),
            ]
        elif head_type == "residual_mlp":
            layers = [
                nn.LayerNorm(in_dim),
                nn.Linear(in_dim, out_dim),
                nn.GELU(),
                nn.Linear(out_dim, out_dim),
                nn.Dropout(dropout),
                nn.LayerNorm(out_dim),
            ]
        elif head_type == "deep":
            layers = [
                nn.LayerNorm(in_dim),
                nn.Linear(in_dim, hidden_dim),
                nn.GELU(),
                nn.Dropout(dropout),
                nn.Linear(hidden_dim, hidden_dim),
                nn.GELU(),
                nn.Dropout(dropout),
                nn.Linear(hidden_dim, out_dim),
                nn.LayerNorm(out_dim),
            ]
        else:
            raise ValueError(f"Unsupported projection head type: {head_type}")
        self.net = nn.Sequential(*layers)

    def forward_pre_normalize(self, x: torch.Tensor) -> torch.Tensor:
        x = x.float()
        if self.head_type == "residual_mlp":
            normalized = self.net[0](x)
            projected = self.net[1](normalized)
            hidden = self.net[2](projected)
            hidden = self.net[3](hidden)
            hidden = self.net[4](hidden)
            return self.net[5](hidden + projected)
        return self.net(x)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return F.normalize(self.forward_pre_normalize(x), dim=-1)


class BlockwiseNormalizer(nn.Module):
    def __init__(self, block_dims: list[int], mode: str) -> None:
        super().__init__()
        if not block_dims or any(dim <= 0 for dim in block_dims):
            raise ValueError(f"Invalid molecule block dimensions: {block_dims}")
        if mode not in ("none", "l2", "block_l2", "global_l2", "layernorm"):
            raise ValueError(f"Unsupported block normalization: {mode}")
        self.block_dims = tuple(block_dims)
        self.mode = mode
        self.layer_norms = (
            nn.ModuleList([nn.LayerNorm(dim) for dim in block_dims])
            if mode == "layernorm"
            else nn.ModuleList()
        )

    def forward(self, values: torch.Tensor) -> torch.Tensor:
        if values.shape[-1] != sum(self.block_dims):
            raise ValueError(
                f"Molecule feature width does not match blocks: {values.shape[-1]} != {sum(self.block_dims)}"
            )
        if self.mode == "none":
            return values
        if self.mode == "global_l2":
            return F.normalize(values, p=2, dim=-1, eps=1e-12)
        blocks = values.split(self.block_dims, dim=-1)
        if self.mode in ("l2", "block_l2"):
            normalized = [F.normalize(block, p=2, dim=-1, eps=1e-12) for block in blocks]
        else:
            normalized = [layer_norm(block) for layer_norm, block in zip(self.layer_norms, blocks, strict=True)]
        return torch.cat(normalized, dim=-1)


class GatedBlockMoleculeHead(nn.Module):
    """Encode heterogeneous molecule blocks separately, then learn their fusion weights."""

    def __init__(
        self,
        block_dims: list[int],
        branch_dims: list[int],
        out_dim: int,
        fusion_hidden_dim: int,
        dropout: float,
    ) -> None:
        super().__init__()
        if not block_dims or any(dim <= 0 for dim in block_dims):
            raise ValueError(f"Invalid molecule block dimensions: {block_dims}")
        if len(block_dims) != len(branch_dims):
            raise ValueError(
                "Molecule block and branch dimension counts differ: "
                f"{len(block_dims)} != {len(branch_dims)}"
            )
        if any(dim <= 0 for dim in branch_dims):
            raise ValueError(f"Invalid molecule branch dimensions: {branch_dims}")
        if out_dim <= 0 or fusion_hidden_dim <= 0:
            raise ValueError(
                f"Output and fusion dimensions must be positive: {out_dim}, {fusion_hidden_dim}"
            )

        self.block_dims = tuple(int(dim) for dim in block_dims)
        self.branch_dims = tuple(int(dim) for dim in branch_dims)
        self.out_dim = int(out_dim)
        self.fusion_hidden_dim = int(fusion_hidden_dim)
        self.branches = nn.ModuleList(
            [
                nn.Sequential(
                    nn.Linear(block_dim, branch_dim),
                    nn.GELU(),
                    nn.Dropout(dropout),
                    nn.LayerNorm(branch_dim),
                )
                for block_dim, branch_dim in zip(self.block_dims, self.branch_dims, strict=True)
            ]
        )
        self.gate_logits = nn.Parameter(torch.zeros(len(self.block_dims), dtype=torch.float32))
        fused_dim = sum(self.branch_dims)
        self.fused_norm = nn.LayerNorm(fused_dim)
        self.skip = nn.Linear(fused_dim, out_dim)
        self.residual = nn.Sequential(
            nn.Linear(fused_dim, fusion_hidden_dim),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(fusion_hidden_dim, out_dim),
        )
        self.output_norm = nn.LayerNorm(out_dim)

    def split_blocks(self, values: torch.Tensor) -> tuple[torch.Tensor, ...]:
        if values.shape[-1] != sum(self.block_dims):
            raise ValueError(
                f"Molecule feature width does not match blocks: {values.shape[-1]} != {sum(self.block_dims)}"
            )
        return values.split(self.block_dims, dim=-1)

    def gate_values(self) -> torch.Tensor:
        return len(self.block_dims) * torch.softmax(self.gate_logits, dim=0)

    def forward(self, values: torch.Tensor) -> torch.Tensor:
        blocks = self.split_blocks(values.float())
        gates = self.gate_values()
        encoded = [
            branch(block) * gates[index]
            for index, (branch, block) in enumerate(zip(self.branches, blocks, strict=True))
        ]
        fused = self.fused_norm(torch.cat(encoded, dim=-1))
        projected = self.skip(fused) + self.residual(fused)
        return F.normalize(self.output_norm(projected), dim=-1)


class ProjectionModel(nn.Module):
    def __init__(
        self,
        spec_dim: int,
        mol_dim: int,
        hidden_dim: int,
        proj_dim: int,
        dropout: float,
        temperature: float,
        head_type: str,
        mol_block_dims: list[int] | None = None,
        mol_block_normalization: str = "none",
        mol_head_type: str = "shared_mlp",
        mol_branch_dims: list[int] | None = None,
        mol_fusion_hidden_dim: int = 1536,
        mol_block_names: list[str] | None = None,
    ) -> None:
        super().__init__()
        resolved_block_dims = list(mol_block_dims or [mol_dim])
        if sum(resolved_block_dims) != mol_dim:
            raise ValueError(
                f"Molecule feature width does not match blocks: {mol_dim} != {sum(resolved_block_dims)}"
            )
        if mol_block_names is None:
            resolved_block_names = [f"block_{index}" for index in range(len(resolved_block_dims))]
        else:
            resolved_block_names = list(mol_block_names)
        if len(resolved_block_names) != len(resolved_block_dims):
            raise ValueError(
                "Molecule block name and dimension counts differ: "
                f"{len(resolved_block_names)} != {len(resolved_block_dims)}"
            )

        self.mol_head_type = mol_head_type
        self.mol_block_dims = tuple(resolved_block_dims)
        self.mol_block_names = tuple(resolved_block_names)
        self.mol_block_normalization = mol_block_normalization
        self.mol_branch_dims: tuple[int, ...] = ()
        self.mol_fusion_hidden_dim = int(mol_fusion_hidden_dim)
        self.spec_head = ProjectionHead(spec_dim, hidden_dim, proj_dim, dropout, head_type)
        self.mol_input_normalizer = BlockwiseNormalizer(resolved_block_dims, mol_block_normalization)
        if mol_head_type == "shared_mlp":
            self.mol_head = ProjectionHead(mol_dim, hidden_dim, proj_dim, dropout, head_type)
        elif mol_head_type == "block_gated_residual":
            resolved_branch_dims = list(mol_branch_dims or DEFAULT_MOL_BRANCH_DIMS)
            self.mol_branch_dims = tuple(resolved_branch_dims)
            self.mol_head = GatedBlockMoleculeHead(
                resolved_block_dims,
                resolved_branch_dims,
                proj_dim,
                mol_fusion_hidden_dim,
                dropout,
            )
        else:
            raise ValueError(f"Unsupported molecule head type: {mol_head_type}")
        self.log_temperature = nn.Parameter(torch.tensor(math.log(temperature), dtype=torch.float32))

    def project_spec(self, spec: torch.Tensor) -> torch.Tensor:
        return self.spec_head(spec)

    def project_spec_pre_normalize(self, spec: torch.Tensor) -> torch.Tensor:
        return self.spec_head.forward_pre_normalize(spec)

    def project_mol(self, mol: torch.Tensor) -> torch.Tensor:
        return self.mol_head(self.mol_input_normalizer(mol.float()))

    def temperature(self) -> torch.Tensor:
        return self.log_temperature.exp().clamp(min=0.01, max=1.0)

    def molecule_gate_values(self) -> list[float] | None:
        if not isinstance(self.mol_head, GatedBlockMoleculeHead):
            return None
        return [float(value) for value in self.mol_head.gate_values().detach().cpu()]


