def load_jsonl(path: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def load_candidate_sidecar(path: Path) -> dict[str, dict[str, Any]]:
    records = load_jsonl(path)
    sidecar: dict[str, dict[str, Any]] = {}
    for record in records:
        identifier = record.get("identifier")
        if identifier is None:
            continue
        sidecar[str(identifier)] = record
    return sidecar


def load_dreams(path: Path) -> torch.Tensor:
    if path.suffix == ".npy":
        arr = np.load(path)
        return torch.from_numpy(arr).float()
    payload = torch.load(path, map_location="cpu", weights_only=False)
    if isinstance(payload, torch.Tensor):
        return payload.float()
    if isinstance(payload, dict):
        for key in ("embeddings", "dreams_embeddings", "spectra"):
            value = payload.get(key)
            if isinstance(value, torch.Tensor):
                return value.float()
            if isinstance(value, np.ndarray):
                return torch.from_numpy(value).float()
    raise ValueError(f"Could not find DreaMS tensor in {path}")


def load_mol_embeddings(chemberta: dict[str, Any], mol_pooling: str) -> torch.Tensor:
    embeddings = chemberta["embeddings"]
    if mol_pooling == "morgan":
        return embeddings["morgan"].float()
    if mol_pooling == "mean_morgan_concat":
        return torch.cat([embeddings["mean"].float(), embeddings["morgan"].float()], dim=1)
    if mol_pooling == "cls_morgan_concat":
        return torch.cat([embeddings["cls"].float(), embeddings["morgan"].float()], dim=1)
    if mol_pooling == "mean_cls_concat":
        return torch.cat([embeddings["mean"].float(), embeddings["cls"].float()], dim=1)
    if mol_pooling == "mean_cls_morgan_concat":
        return torch.cat(
            [embeddings["mean"].float(), embeddings["cls"].float(), embeddings["morgan"].float()],
            dim=1,
        )
    return embeddings[mol_pooling].float()


